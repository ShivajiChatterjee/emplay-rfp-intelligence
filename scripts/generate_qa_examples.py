"""Generate resumable, genuinely cited Q&A examples through the real workflow."""

from __future__ import annotations

import argparse
import json
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from agents.evidence_verification import claim_evidence_errors
from agents.schemas import Evidence
from workflow import WorkflowRequest, run_workflow


DEFAULT_QUESTION_IDS = (
    "B1-01", "B2-01",  # deadlines
    "B1-03",             # contract term
    "B2-06",             # delivery
    "B1-04", "B2-08",  # warranties
    "B2-02",             # processor specification
    "B1-06",             # device configuration
    "B2-05",             # manufacturer authorization
    "B1-09",             # procurement contact
    "B2-07",             # required documentation
    "B2-04",             # exact product model
)


def _atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(text, encoding="utf-8")
    temporary.replace(path)


def _render_markdown(payload: dict[str, Any]) -> str:
    successes = [item for item in payload["results"] if item["status"] == "success"]
    lines = [
        "# Genuine Cited RFP Q&A Examples",
        "",
        f"Successful cited answers: **{len(successes)}**",
        "",
        (
            "These answers were generated by the production LangGraph Q&A workflow "
            "using bid-isolated hybrid Qdrant retrieval, Cohere reranking, Gemini "
            "structured answering, and local claim/citation verification. They are "
            "not retrieval-evaluation measurements."
        ),
        "",
    ]
    for item in payload["results"]:
        lines.extend([
            f"## {item['id']} — {item['bid_id']}",
            "",
            f"**Status:** `{item['status']}`",
            "",
            f"**Question:** {item['question']}",
            "",
        ])
        if item.get("answer"):
            lines.extend([
                f"**Answer:** {item['answer']}",
                "",
                f"**Confidence:** {item.get('confidence', 0.0)}",
                "",
                "**Sources:**",
                "",
            ])
            for source in item.get("sources", []):
                lines.append(
                    f"- `{source['file']}`, physical page {source['page']}, "
                    f"evidence `{source['chunk_id']}`"
                )
        if item.get("error"):
            lines.append(f"**Error:** {item['error']}")
        if item.get("run_id"):
            lines.extend([
                "",
                f"Run ID: `{item['run_id']}`",
                "",
                f"Trace: `{item.get('trace_path')}`",
            ])
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _save(payload: dict[str, Any], json_path: Path, markdown_path: Path) -> None:
    payload["updated_at"] = datetime.now(timezone.utc).isoformat()
    _atomic_write(json_path, json.dumps(payload, indent=2, ensure_ascii=False))
    _atomic_write(markdown_path, _render_markdown(payload))


def _cited_evidence(result: dict[str, Any], bid_id: str) -> list[Evidence]:
    answer = result.get("qa_answer")
    if answer is None:
        return []
    evidence = result.get("evidence", {}).get(f"{bid_id}::qa", [])
    cited_ids = {source.chunk_id for source in answer.sources}
    return [item for item in evidence if item.chunk_id in cited_ids]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--questions", type=Path, default=Path("evaluation/questions.json"))
    parser.add_argument("--ids", nargs="+", default=list(DEFAULT_QUESTION_IDS))
    parser.add_argument("--target-successes", type=int, default=10)
    parser.add_argument("--max-questions", type=int, default=12)
    parser.add_argument("--output-json", type=Path, default=Path("outputs/qa_examples.json"))
    parser.add_argument("--output-markdown", type=Path, default=Path("outputs/qa_examples.md"))
    parser.add_argument("--runs-dir", type=Path, default=Path("outputs/qa_runs"))
    args = parser.parse_args()

    questions = json.loads(args.questions.read_text(encoding="utf-8"))
    by_id = {item["id"]: item for item in questions}
    unknown = [item for item in args.ids if item not in by_id]
    if unknown:
        parser.error(f"Unknown evaluation question IDs: {unknown}")
    if args.target_successes < 1 or args.max_questions < 1:
        parser.error("target-successes and max-questions must be positive")

    if args.output_json.exists():
        payload = json.loads(args.output_json.read_text(encoding="utf-8"))
    else:
        payload = {
            "schema_version": 1,
            "created_at": datetime.now(timezone.utc).isoformat(),
            "question_dataset": str(args.questions),
            "target_successes": args.target_successes,
            "results": [],
        }
    existing = {item["id"]: item for item in payload["results"]}
    attempted = 0

    for question_id in args.ids:
        successes = sum(item["status"] == "success" for item in payload["results"])
        if successes >= args.target_successes or attempted >= args.max_questions:
            break
        if existing.get(question_id, {}).get("status") == "success":
            continue

        question = by_id[question_id]
        bid_id = question["bid_id"]
        started = time.perf_counter()
        record: dict[str, Any] = {
            "id": question_id,
            "bid_id": bid_id,
            "question": question["question"],
            "status": "incomplete",
            "attempted_at": datetime.now(timezone.utc).isoformat(),
        }
        try:
            result = run_workflow(
                WorkflowRequest(
                    mode="ask",
                    bid_folders=(Path("data") / bid_id,),
                    question=question["question"],
                    output_dir=args.runs_dir,
                    allow_query_rewrite=False,
                    semantic_validation=False,
                    max_retries=0,
                )
            )
            answer = result.get("qa_answer")
            cited = _cited_evidence(result, bid_id)
            verification_errors: list[str] = []
            if answer and answer.answer != "Not found in documents" and cited:
                _, verification_errors = claim_evidence_errors(answer.answer, cited)
            success = bool(
                answer
                and answer.answer != "Not found in documents"
                and answer.sources
                and len(cited) == len({item.chunk_id for item in answer.sources})
                and not verification_errors
            )
            record.update({
                "status": "success" if success else "incomplete",
                "answer": answer.answer if answer else None,
                "confidence": answer.confidence if answer else 0.0,
                "notes": answer.notes if answer else "Workflow returned no Q&A answer.",
                "sources": [item.model_dump(mode="json") for item in answer.sources] if answer else [],
                "verification_errors": verification_errors,
                "run_id": result.get("run_id"),
                "trace_path": str(result.get("workflow_trace_path")),
                "warnings": result.get("warnings", []),
                "errors": result.get("errors", []),
            })
        except Exception as exc:
            record.update({
                "status": "incomplete",
                "error": f"{type(exc).__name__}: {exc}",
            })
        record["latency_ms"] = round((time.perf_counter() - started) * 1000, 2)

        payload["results"] = [
            item for item in payload["results"] if item["id"] != question_id
        ] + [record]
        existing[question_id] = record
        attempted += 1
        _save(payload, args.output_json, args.output_markdown)
        print(
            f"{question_id}: {record['status']} "
            f"({sum(item['status'] == 'success' for item in payload['results'])}/"
            f"{args.target_successes} successful)",
            flush=True,
        )

    _save(payload, args.output_json, args.output_markdown)
    successes = sum(item["status"] == "success" for item in payload["results"])
    print(f"Saved {successes} successful cited answers to {args.output_json}")
    if successes < args.target_successes:
        raise SystemExit(2)


if __name__ == "__main__":
    main()
